// Regenerates notes/README.md from the H1 of every note. Run after adding one.
// Usage: node scripts/build-notes-index.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
const files = readdirSync('notes').filter((f) => f.endsWith('.md') && f !== 'README.md').sort()
const rows = files.map((f) => {
  const body = readFileSync('notes/' + f, 'utf8')
  const h1 = (body.match(/^#\s+(.+)$/m) || [, f.replace(/\.md$/, '')])[1].trim()
  const date = (f.match(/^(\d{4}-\d{2}-\d{2})/) || [])[1] || ''
  return { f, h1, date, lines: body.split('\n').length }
})
// Newest first; undated thread docs pinned to the top.
const threads = rows.filter((r) => !r.date)
const dated = rows.filter((r) => r.date).sort((a, b) => b.date.localeCompare(a.date) || a.f.localeCompare(b.f))

let out = `# Notes index

Engineering notes for KawmHmoob mobile. One file per piece of work: what was
done, **why**, what broke, and what is still open. Newest first.

AUTO-GENERATED by \`node scripts/build-notes-index.mjs\` — re-run it after adding
a note rather than editing this file by hand.

`
if (threads.length) {
  out += `## Thread docs — start here\n\nLong-running stories that span many days. Each links out to the dated notes.\n\n`
  for (const r of threads) out += `- **[${r.h1}](${r.f})** · ${r.lines} lines\n`
  out += '\n'
}
out += `## By date\n\n`
let year = ''
for (const r of dated) {
  const m = r.date.slice(0, 7)
  if (m !== year) { year = m; out += `\n### ${m}\n\n` }
  out += `- \`${r.date}\` [${r.h1}](${r.f})\n`
}
out += `\n---\n\n${rows.length} notes, ${rows.reduce((a, r) => a + r.lines, 0).toLocaleString()} lines.\n`
writeFileSync('notes/README.md', out)
console.log('notes/README.md written -', rows.length, 'notes')
