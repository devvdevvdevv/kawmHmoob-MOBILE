// Regenerates src/lib/audioMap.js from whatever .mp3/.wav files live under assets/audio/.
//
// The data stores audio as WEB paths ("/assets/audio/.../foo.mp3"). Metro can't
// require() a runtime-variable path, so we emit one STATIC require() per file,
// keyed by that web path. Run this whenever the bundled audio set changes:
//
//   node scripts/generate-audio-map.js
//
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const AUDIO_DIR = path.join(ROOT, 'assets', 'audio')
const OUT = path.join(ROOT, 'src', 'lib', 'audioMap.js')

function walk(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(p, acc)
    // ⚠️ .wav IS BUNDLED TOO — added 2026-09-12 for the lesson recordings, which
    // arrive as raw studio .wav and ship unconverted (no ffmpeg on the authoring
    // machine). A .wav is roughly 10x the size of the equivalent .mp3, so
    // converting them and re-running this script is the cheapest bundle win
    // available. Nothing else needs to change: the data keys on the path, and
    // expo-audio plays both.
    else if (/\.(mp3|wav)$/.test(entry.name.toLowerCase())) acc.push(p)
  }
  return acc
}

const files = walk(AUDIO_DIR)
  .map((abs) => path.relative(AUDIO_DIR, abs).split(path.sep).join('/')) // "consonants/…/x.mp3"
  .sort()

const lines = files.map((rel) => {
  const webPath = `/assets/audio/${rel}` // the key the data uses
  const reqPath = `../../assets/audio/${rel}` // relative to src/lib/audioMap.js
  return `  '${webPath}': require('${reqPath}'),`
})

const out = `// AUTO-GENERATED by scripts/generate-audio-map.js — do not edit by hand.
// Maps each web audio path to a bundled asset via a STATIC require() (Metro needs
// literal require strings). Regenerate with: node scripts/generate-audio-map.js
// Files live under assets/audio/ mirroring the web /assets/audio/ tree.
export const AUDIO_MAP = {
${lines.join('\n')}
}
`

fs.writeFileSync(OUT, out)
console.log(`wrote ${files.length} entries to ${path.relative(ROOT, OUT)}`)
